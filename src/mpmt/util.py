"""Bloom filter parameter calculation.

@author  mincy
"""

import math

_BF_SET_SIZE_MIN     = 2 ** 10  # minimum allowed set size
_BF_SET_SIZE_MAX     = 2 ** 25  # maximum allowed set size
_BF_FPR_EXPONENT_MIN = -12      # finest  false-positive rate
_BF_FPR_EXPONENT_MAX = -1       # coarsest false-positive rate
_BF_FPR_MANTISSA_MIN = 1.0      # mantissa lower bound (inclusive)
_BF_FPR_MANTISSA_MAX = 10.0     # mantissa upper bound (exclusive)


def bf_param(set_size: int, fpr_mantissa: float, fpr_exponent: int):
    """Calculate Bloom filter size and hash-function count.

    Parameters
    ----------
    set_size : int
        Expected maximum size of the set.
    fpr_mantissa : float
        Mantissa of the false-positive rate, e.g. ``1.0`` in ``1.0e-3``.
    fpr_exponent : int
        Exponent of the false-positive rate, e.g. ``-3`` in ``1.0e-3``.

    Returns
    -------
    tuple[int, int, int, int]
        ``(bf_size, bf_size_log2up, hf_num, hf_num_log2up)``
    """
    if set_size < _BF_SET_SIZE_MIN:
        raise ValueError(
            f"set_size must be >= {_BF_SET_SIZE_MIN}"
        )
    
    if set_size > _BF_SET_SIZE_MAX:
        raise ValueError(
            f"set_size must be <= {_BF_SET_SIZE_MAX}"
        )
    
    if not (_BF_FPR_EXPONENT_MIN <= fpr_exponent <= _BF_FPR_EXPONENT_MAX):
        raise ValueError(
            f"fpr_exponent must be in "
            f"[{_BF_FPR_EXPONENT_MIN}, {_BF_FPR_EXPONENT_MAX}]"
        )

    if not (_BF_FPR_MANTISSA_MIN <= fpr_mantissa < _BF_FPR_MANTISSA_MAX):
        raise ValueError(
            f"fpr_mantissa={fpr_mantissa} must be in "
            f"[{_BF_FPR_MANTISSA_MIN}, {_BF_FPR_MANTISSA_MAX})"
        )

    fpr = fpr_mantissa * (10 ** fpr_exponent)

    ln2 = math.log(2)
    bf_size_raw = set_size * (-math.log(fpr) / (ln2 * ln2))
    bf_size = round(bf_size_raw)
    bf_size_log2up = math.ceil(math.log2(bf_size))
    hf_num = round((bf_size_raw / set_size) * ln2)
    hf_num_log2up = math.floor(math.log2(hf_num)) + 1

    return bf_size, bf_size_log2up, hf_num, hf_num_log2up


